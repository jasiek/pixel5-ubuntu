"""Generate the dtbo "sink" dtsi for a mainline redfin DTB.

    scripts/gen-dtbo-sink.py firmware/dtbo.img > kernel/mainline/dts/sm7250-google-redfin-dtbo-sink.dtsi

The bootloader always applies an overlay from the stock dtbo partition to the
kernel's DTB, and refuses to boot when one of the overlay's label references
(its __fixups__) is missing from the base DTB's __symbols__
(docs/research/mainline-boot.md, section 1.3). The sink gives every label
any of the overlays uses an empty node under /redfin-dtbo-sink, with
hand-written __symbols__ pointing there, so the overlay applies into the sink
and Linux ignores it (no compatible). The DTB is built without dtc -@, so
real mainline labels are never exported and the overlay cannot touch them.

Reads only label names from the overlays; no vendor data is copied.
"""
import struct
import sys

FDT_MAGIC, DTBO_MAGIC = 0xD00DFEED, 0xD7B7AB1E
FDT_BEGIN_NODE, FDT_END_NODE, FDT_PROP, FDT_NOP, FDT_END = 1, 2, 3, 4, 9


def fdt_fixup_labels(blob):
    """Property names of /__fixups__ in one FDT."""
    magic, _size, off_struct, off_strings = struct.unpack_from(">IIII", blob, 0)
    assert magic == FDT_MAGIC, "not an FDT"
    strings = blob[off_strings:]
    pos, path, labels = off_struct, [], []
    while True:
        tag, = struct.unpack_from(">I", blob, pos)
        pos += 4
        if tag == FDT_BEGIN_NODE:
            end = blob.index(b"\0", pos)
            path.append(blob[pos:end].decode())
            pos = (end + 4) & ~3
        elif tag == FDT_END_NODE:
            path.pop()
        elif tag == FDT_PROP:
            length, nameoff = struct.unpack_from(">II", blob, pos)
            pos = (pos + 8 + length + 3) & ~3
            if path == ["", "__fixups__"]:
                name = strings[nameoff:strings.index(b"\0", nameoff)].decode()
                labels.append(name)
        elif tag == FDT_NOP:
            pass
        elif tag == FDT_END:
            return labels
        else:
            raise ValueError(f"bad FDT tag {tag}")


def dtbo_entries(img):
    magic, _total, _hdr, entry_size, count, entries_off = struct.unpack_from(">6I", img, 0)
    assert magic == DTBO_MAGIC, "not a dtbo image"
    for k in range(count):
        dt_size, dt_off = struct.unpack_from(">II", img, entries_off + k * entry_size)
        yield img[dt_off:dt_off + dt_size]


def main():
    img = open(sys.argv[1], "rb").read()
    labels, count = [], 0
    for blob in dtbo_entries(img):
        count += 1
        for name in fdt_fixup_labels(blob):
            if name not in labels:
                labels.append(name)
    node = {l: l.replace("_", "-").lower() for l in labels}
    w = sys.stdout.write
    w("// SPDX-License-Identifier: GPL-2.0-only\n")
    w("/*\n * Sink for the stock redfin dtbo overlays. Generated by\n"
      " * scripts/gen-dtbo-sink.py from firmware/dtbo.img; do not edit.\n *\n"
      f" * Every label the {count} overlays reference ({len(labels)} names, the union of\n"
      " * their __fixups__) points at an empty node under /redfin-dtbo-sink, so\n"
      " * whichever overlay the bootloader applies lands there. No compatible:\n"
      " * Linux creates no devices below it. Hand-written __symbols__ (no dtc -@):\n"
      " * real mainline nodes are never exported, so the overlay cannot touch\n"
      " * them even where label names overlap (tlmm, soc, spmi_bus, ...).\n"
      " * docs/research/mainline-boot.md, section 1.3.\n */\n\n/ {\n")
    w("\tredfin-dtbo-sink {\n")
    w("\t\t/* Referenced so dtc gives every sink node a phandle: libfdt's\n"
      "\t\t * fixup step needs one on each target. */\n")
    refs = " ".join(f"&sink_{l}" for l in labels)
    w(f"\t\tsink-refs = <{refs}>;\n\n")
    for l in labels:
        w(f"\t\tsink_{l}: {node[l]} {{}};\n")
    w("\t};\n\n\t__symbols__ {\n")
    for l in labels:
        w(f'\t\t{l} = "/redfin-dtbo-sink/{node[l]}";\n')
    w("\t};\n};\n")
    print(f"{count} overlays, {len(labels)} labels", file=sys.stderr)


main()
